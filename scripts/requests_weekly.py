#!/usr/bin/env python3
"""Weekly product-request queue: rank `missing-product` GitHub issues plus exported search misses into team/queue/requests.md,
and DRAFT (never post) close-out comments for requests whose product is now published.

  python3 -I scripts/requests_weekly.py [--repo OWNER/NAME] [--misses FILE] [--issues-json FILE] [--out PATH]

--misses  : JSONL ({"q": "...", "n": 3}, n optional) or CSV/TSV-less lines "count<TAB>query" exported from the miss counter.
--issues-json : use a saved `gh issue list --json number,title,body,createdAt,url` dump instead of calling gh (testing/offline).
gh is used read-only (`gh issue list`); this script never comments, labels or closes anything.
Published check: an identifier-like token of the request found in docs/api/v1/lookup/identifiers.json (exact, case-insensitive).
"""
import argparse, collections, json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOOKUP = ROOT / "docs" / "api" / "v1" / "lookup" / "identifiers.json"
SITE = ROOT / "docs" / "site.json"


def norm(text):
    return re.sub(r"\s+", " ", text.strip().lower())


def tokens(text):
    out = []
    for word in re.split(r"[\s,;()\[\]\"]+", text.upper()):
        value = re.sub(r"[\s.\-_/]", "", word)
        if re.fullmatch(r"[A-Z0-9]{5,24}", value) and re.search(r"[A-Z]", value) and re.search(r"\d", value):
            out.append(value)
        elif re.fullmatch(r"\d{8,14}", value):
            out.append(value.zfill(14))
    return out


def load_lookup():
    if not LOOKUP.exists():
        return {}
    index = {}
    for key, ids in json.loads(LOOKUP.read_text()).items():
        value = key.split(":", 1)[-1]
        index.setdefault(re.sub(r"[\s.\-_/]", "", value).upper(), ids)
    return index


def issue_query(issue):
    """The request's search text: the `query` field of the catalogue payload when present, else the title."""
    body = issue.get("body") or ""
    m = re.search(r'"query"\s*:\s*"((?:[^"\\]|\\.)*)"', body)
    if m:
        try:
            return json.loads(f'"{m.group(1)}"')
        except ValueError:
            pass
    return re.sub(r"^\s*Missing product:\s*", "", issue.get("title", ""), flags=re.I)


def read_issues(args):
    if args.issues_json:
        return json.loads(Path(args.issues_json).read_text())
    cmd = ["gh", "issue", "list", "--label", "missing-product", "--state", "open", "--limit", "200",
           "--json", "number,title,body,createdAt,url"]
    repo = args.repo or json.loads(SITE.read_text()).get("repo")
    if repo:
        cmd += ["--repo", repo]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode:
        print(f"gh failed ({proc.stderr.strip()[:200]}); continuing with misses only", file=sys.stderr)
        return []
    return json.loads(proc.stdout)


def read_misses(path):
    counts = collections.Counter()
    if not path:
        return counts
    for line in Path(path).read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("{"):
            row = json.loads(line)
            counts[norm(row.get("q", ""))] += int(row.get("n", 1))
        else:
            m = re.match(r"(\d+)\s+(.*)", line)
            counts[norm(m.group(2) if m else line)] += int(m.group(1)) if m else 1
    return counts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo"); ap.add_argument("--misses"); ap.add_argument("--issues-json")
    ap.add_argument("--out", default=str(ROOT / "team" / "queue" / "requests.md"))
    args = ap.parse_args()
    lookup = load_lookup()
    issues = read_issues(args)
    misses = read_misses(args.misses)
    entries = {}   # normalized query -> {issues:[...], misses:int, query:str}
    for issue in issues:
        q = issue_query(issue)
        e = entries.setdefault(norm(q), {"query": q, "issues": [], "misses": 0})
        e["issues"].append(issue)
    for q, n in misses.items():
        e = entries.setdefault(q, {"query": q, "issues": [], "misses": 0})
        e["misses"] += n
    for e in entries.values():
        found = [(t, lookup[t]) for t in tokens(e["query"]) if t in lookup]
        e["published"] = found[0] if found else None
        e["score"] = len(e["issues"]) * 5 + e["misses"]
    ranked = sorted(entries.values(), key=lambda e: (-e["score"], e["query"]))
    open_rows = [e for e in ranked if not e["published"]]
    done = [e for e in ranked if e["published"] and e["issues"]]
    out = ["# Product request queue", "",
           f"Generated by `scripts/requests_weekly.py`: {len(issues)} open missing-product issue(s), {sum(misses.values())} search miss(es). "
           "Score = 5 per issue + 1 per miss. Nothing here has been posted.", "", "## To add (ranked)", ""]
    out += ["| Score | Issues | Misses | Query |", "|---|---|---|---|"]
    for e in open_rows[:100]:
        refs = ", ".join(f"#{i['number']}" for i in e["issues"]) or "-"
        out.append(f"| {e['score']} | {refs} | {e['misses']} | {e['query'][:90].replace('|', '/')} |")
    if not open_rows:
        out.append("| - | - | - | (empty) |")
    out += ["", "## Now published: draft close-out comments (do not post automatically)", ""]
    for e in done:
        token, ids = e["published"]
        for issue in e["issues"]:
            out += [f"### #{issue['number']} {issue.get('title', '')[:80]}", "",
                    f"> Thanks for the request. {token} is now in the dataset (product id: {', '.join(ids[:3])}). "
                    "Search for it by model number on the site, and open a new issue if any value looks wrong. Closing as done.", ""]
    if not done:
        out.append("(none)")
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(out) + "\n")
    print(f"wrote {args.out}: {len(open_rows)} to add, {len(done)} publishable close-outs")


if __name__ == "__main__":
    main()
