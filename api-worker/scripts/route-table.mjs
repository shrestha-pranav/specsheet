// Generates the README route table from test/route-matrix.json (D3.5).  node scripts/route-table.mjs [--write]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const here = import.meta.dirname;
const M = JSON.parse(readFileSync(resolve(here, "../test/route-matrix.json"), "utf8"));
const cell = (e) => (e ? `${e.status}${e.error ? ` \`${e.error}\`` : ""}${e.retry_after ? " +RA" : ""}` : "");

export function routeTable() {
  const head = `| Row | Request | ${M.modes.join(" | ")} | Quota | Listed (off) |\n|${"---|".repeat(M.modes.length + 4)}`;
  const rows = M.rows.map((r) => {
    const q = r.query ? "?" + Object.keys(r.query).join("&") : "";
    const req = `${r.method} ${r.path}${q}${r.tool ? ` (${r.tool})` : ""}${r.setup ? ` [${r.setup}]` : ""}`;
    return `| ${r.id} | \`${req.replace(/\|/g, "\\|")}\` | ${M.modes.map((m) => cell(r.expect[m])).join(" | ")} | ${r.quota} | ${r.discovery === null ? "n/a" : r.discovery ? "yes" : "no"} |`;
  });
  return `<!-- route-table:start -->\n<!-- generated by scripts/route-table.mjs from test/route-matrix.json; do not edit by hand -->\n${head}\n${rows.join("\n")}\n<!-- route-table:end -->`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const t = routeTable();
  if (process.argv.includes("--write")) {
    const p = resolve(here, "../README.md");
    const s = readFileSync(p, "utf8");
    const a = s.indexOf("<!-- route-table:start -->"), b = s.indexOf("<!-- route-table:end -->") + "<!-- route-table:end -->".length;
    if (a < 0) throw new Error("README lacks <!-- route-table:start --> markers");
    writeFileSync(p, s.slice(0, a) + t + s.slice(b));
  } else console.log(t);
}
